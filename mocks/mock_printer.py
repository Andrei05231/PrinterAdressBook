    def create_session(self, username, password):
        """Create a new session"""
        # Simple auth check
        if username == "AdminAdmin" and password == "1234567812345678":
            session_id = str(uuid.uuid4())
            h_token = str(uuid.uuid4())
            self.sessions[session_id] = {
                "username": username,
                "created_at": time.time(),
                "authenticated": True
            }
            self.h_tokens[session_id] = h_token
            return session_id, h_token
        return None, None
    
    def validate_session(self, session_id):
        """Check if session is valid"""
        return session_id in self.sessions and self.sessions[session_id]["authenticated"]
    
    def get_h_token(self, session_id):
        """Get h_token for session"""
        return self.h_tokens.get(session_id)
    
    def create_export_job(self, session_id):
        """Create an export job"""
        if not self.validate_session(session_id):
            return None
        
        job_id = str(uuid.uuid4())
        self.jobs[job_id] = {
            "type": "export",
            "status": "running",
            "created_at": time.time(),
            "session_id": session_id
        }
        return job_id
    
    def create_import_job(self, session_id):
        """Create an import job"""
        if not self.validate_session(session_id):
            return None
            
        job_id = str(uuid.uuid4())
        self.jobs[job_id] = {
            "type": "import", 
            "status": "running",
            "created_at": time.time(),
            "session_id": session_id
        }
        return job_id
    
    def get_job_status(self, job_id):
        """Get job status - simulate completion after 10 seconds"""
        if job_id not in self.jobs:
            return None
        
        job = self.jobs[job_id]
        elapsed = time.time() - job["created_at"]
        
        if elapsed > 10:  # Job completes after 10 seconds
            job["status"] = "completed"
        
        return job
    
    def export_address_book(self):
        """Export address book to TSV format"""
        lines = []
        
        # Add metadata
        lines.append("# Generated by Mock Konica Printer")
        lines.append(f"# Export Time: {datetime.now()}")
        lines.append("")
        
        # Add header
        header = [
            "AbbrNo", "Name", "SendMode", "SMBAddress", "SMBFolder",
            "SMBLoginUser", "SMBLoginPassword", "SearchKey", "UseReferLicence",
            "ReferGroupNo", "ReferPossibleLevel", "WellUse", "Pinyin"
        ]
        lines.append("\t".join(header))
        
        # Add data
        for entry in self.address_book:
            row = [entry.get(col, "") for col in header]
            lines.append("\t".join(row))
        
        lines.append("@End")
        
        # Create temporary file
        temp_file = tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.txt', encoding='utf-16-le')
        temp_file.write("\n".join(lines))
        temp_file.close()
        
        # Store with token
        token = str(uuid.uuid4())
        self.exported_files[token] = temp_file.name
        
        return token
    
    def delete_address_item(self, item_id):
        """Delete an address book item by AbbrNo"""
        self.address_book = [item for item in self.address_book if item.get("AbbrNo") != item_id]
        return True

