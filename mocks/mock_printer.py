@app.route('/wcd/login.cgi', methods=['POST'])
def login():
    """Handle login requests"""
    username = request.form.get('username')
    password = request.form.get('password')
    
    print(f"[MOCK] Login attempt: {username}")
    
    session_id, h_token = printer.create_session(username, password)
    
    if session_id:
        # Response where <Item> text is 200 (so check_response returns 200)
        response = make_response(
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<Response><Message><Item Code="200">200</Item></Message></Response>'
        )
        response.set_cookie('ID', session_id, domain=request.host.split(':')[0])
        print(f"[MOCK] Login successful for {username}, session: {session_id}")
        return response
    else:
        # Authentication failed
        response = make_response(
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<Response><Message><Item Code="401">Authentication failed</Item></Message></Response>'
        )
        print(f"[MOCK] Login failed for {username}")
        return response


@app.route('/wcd/a_user.cgi', methods=['POST'])
def logout():
    """Handle logout requests"""
    session_id = request.cookies.get('ID')
    
    if session_id and session_id in printer.sessions:
        del printer.sessions[session_id]
        if session_id in printer.h_tokens:
            del printer.h_tokens[session_id]
        print(f"[MOCK] Logout successful for session: {session_id}")
        return '<?xml version="1.0" encoding="UTF-8"?><Response><Message><Item Code="200">Logout successful</Item></Message></Response>'
    
    return '<?xml version="1.0" encoding="UTF-8"?><Response><Message><Item Code="400">No valid session</Item></Message></Response>'

